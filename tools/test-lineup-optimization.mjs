import assert from 'node:assert/strict';
import { createSimulation } from './bench-era-baseline.mjs';

const { context:c, state, rosters } = createSimulation(2016, 42);
c.getHupuDisplayName = () => 'Lineup Test User';
const player = (name, ovr, pos) => ({ name, ovr, pos, FIN:80, HAN:80, PAS:80, ATH:80 });
rosters.TEST = [player('Flexible guard',99,'PG/SG'),player('Point guard',98,'PG'),player('Wing',88,'SG/SF'),player('Forward',86,'SF/PF'),player('Big',84,'PF/C'),player('Center',83,'C')];
const lineup=c.calcTeamLineup('TEST');
assert.deepEqual(Object.values(lineup.starters).map(p=>p.name), ['Point guard','Flexible guard','Wing','Forward','Big']);
assert.equal(c.calcTeamLineup('TEST'),lineup,'unchanged inputs should reuse a lineup');
state.careerTeam='TEST';state.position='PG';state.finalOVR=70;state.attrs={FIN:70,HAN:70,PAS:70,ATH:70};
const before=c.calcTeamLineup('TEST');
assert.equal(before.isUserStarter,false);
assert.equal(before.bench[0]._isUser,true);
assert.equal(before.bench.filter(p=>p._isUser).length,1);
state.attrs.FIN=89;
const after=c.calcTeamLineup('TEST');
assert.notEqual(after,before,'training must refresh a cached user even when displayed OVR is unchanged');
assert.equal(after.allPlayers.find(p=>p._isUser).FIN,89);
state.careerTeam='LAL';state.finalOVR=90;
const activeBaseline=c.getSimulationPowerBaseline();
state.attrs.FIN=95;
const trainedBaseline=c.getSimulationPowerBaseline();
assert.notEqual(trainedBaseline,activeBaseline,'league power centering must see the same updated user attributes');
assert.ok(trainedBaseline.offense>activeBaseline.offense,'training should reach the production league power average');
console.log('Lineup optimization passed: flexible-position assignment, user bench ordering, cache reuse and training refresh.');
